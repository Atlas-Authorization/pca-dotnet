using System.Globalization;
using System.Runtime;
using System.IO.Compression;
using System.Text;
using AtlasPca;
using Xunit;
using D = System.Collections.Generic.Dictionary<string, object?>;
using L = System.Collections.Generic.List<object?>;

namespace AtlasPca.Corpus.Tests;

/// <summary>Shared harness of the base differential oracles: test-data/base-&lt;module&gt;.json.gz = {cases: [{fn, name, args, out}]}
/// written by the TypeScript reference. Bytes are {"$bytes": b64url}; a reference throw is {"$throws": message, code?} (the native
/// must refuse; when <c>code</c> is present a thrown refusal must carry that code; a refusal by value carries none). fn names ending in <c>@suspect</c> are reported, never failed.</summary>
static class Base
{
    /// <summary>A mapper returns this when the native refuses by value (null / false / an error result) where the reference throws.</summary>
    public static readonly object Refused = new();

    // one module at a time (the assembly runs its tests serially, a class reads one module): all ten parsed oracles are ~3 GiB,
    // over the mutation runs' per-test-host GC heap cap
    static readonly object Gate = new();
    // two fields, no local copy: an unoptimized (tier-0) frame keeps every local alive to method end, and a local holding the old module
    // while the next one parses puts both in the heap (an OutOfMemoryException on the unmutated source, shard 6 of run 42109424696)
    static string? LoadedModule;
    static List<D>? LoadedCases;

    public static List<D> Cases(string module)
    {
        lock (Gate)
        {
            if (LoadedModule == module) return LoadedCases!;
            LoadedModule = null;
            LoadedCases = null;
            GCSettings.LargeObjectHeapCompactionMode = GCLargeObjectHeapCompactionMode.CompactOnce;
            GC.Collect();
            // "ref-<pkg>" names a package oracle file as is; anything else is a base module
            LoadedModuleLoading = module;
            var file = (module.StartsWith("ref-", StringComparison.Ordinal) ? module : "base-" + module) + ".json.gz";
            // ref-dpop-rsa is generated by CI (never committed): PCA_DPOP_RSA_CORPUS names it directly
            if (module == RsaModule && Environment.GetEnvironmentVariable("PCA_DPOP_RSA_CORPUS") is { Length: > 0 } rsa)
            {
                LoadedCases = ReadCases(rsa);
                Clocks[module] = LastClock;
                Committed[module] = LoadedCases.Count;
                LoadedModule = module;
                return LoadedCases;
            }
            var d = AppContext.BaseDirectory;
            for (int i = 0; i < 12 && d != null; i++, d = Path.GetDirectoryName(d))
            {
                var f = Path.Combine(d, "test-data", file);
                if (!File.Exists(f)) f = Path.Combine(d, "AtlasPca.Corpus.Tests", "test-data", file);
                if (!File.Exists(f)) continue;
                LoadedCases = ReadCases(f); // the unmutated reader: this cache outlives mutants
                Clocks[module] = LastClock;
                ClockCaseSets[module] = LastClockCases;
                int committed = LoadedCases.Count;
                if (GenPath(module, Path.GetDirectoryName(f)!) is { } g && File.Exists(g)) LoadedCases.AddRange(ReadCases(g));
                // the same functions replayed over the corpora the other language lanes generated: their cases are appended to the module's own
                if (VariantCorpora.TryGetValue(module, out var variants))
                    foreach (var v in variants)
                    {
                        var vc = ReadCases(Path.Combine(Path.GetDirectoryName(f)!, v + ".json.gz"));
                        committed += vc.Count;
                        LoadedCases.AddRange(vc);
                    }
                Committed[module] = committed;
                LoadedModule = module;
                return LoadedCases;
            }
            throw new FileNotFoundException("test-data/" + file);
        }
    }

    static readonly Dictionary<string, int> Committed = new();

    /// <summary>The generator clock (epoch ms) when a corpus header carries no "clockMs": the reference generator's default.</summary>
    public const double FallbackClockMs = 1_700_000_000_000.0;

    /// <summary>The scripted clock of the scenario oracles (their own T0 constant: every scripted step, stored record and request is stamped from it), distinct from the
    /// frozen wall clock a library reads by default (the header's clockMs).</summary>
    public const long OracleT0 = 1_800_000_000_000;

    /// <summary>The frozen clock a corpus header line (everything up to the opening bracket of "cases") records as "clockMs", else <see cref="FallbackClockMs"/>.</summary>
    public static double ClockOfHeader(string head) =>
        ((D)FixtureJson.Parse(head + "]}")!).GetValueOrDefault("clockMs") is Num n && double.TryParse(n.Raw, NumberStyles.Float, CultureInfo.InvariantCulture, out var ms) && double.IsFinite(ms) ? ms : FallbackClockMs;

    /// <summary>The case names a corpus header lists in "clockCases" (results that depend on the frozen clock); none when the header has no such member.</summary>
    public static HashSet<string> ClockCasesOfHeader(string head) =>
        ((D)FixtureJson.Parse(head + "]}")!).GetValueOrDefault("clockCases") is L l ? l.OfType<string>().ToHashSet(StringComparer.Ordinal) : new HashSet<string>(StringComparer.Ordinal);

    static readonly Dictionary<string, HashSet<string>> ClockCaseSets = new();
    static HashSet<string> LastClockCases = new();

    /// <summary>Whether the corpus header names this case as clock-dependent. Every replay already runs all of a module's cases under its frozen clock, so this is for assertions.</summary>
    public static bool IsClockCase(string module, string name)
    {
        lock (Gate) { Cases(module); return ClockCaseSets.TryGetValue(module, out var s) && s.Contains(name); }
    }

    static readonly Dictionary<string, double> Clocks = new();
    static double LastClock;

    /// <summary>The one clock accessor of the replays: the frozen clock of the module's own corpus file (its header's clockMs).</summary>
    public static double ClockMs(string module)
    {
        lock (Gate)
        {
            Cases(module);
            return Clocks[module];
        }
    }

    /// <summary>How many cases the module's committed corpora hold (its own file and its variant files; a corpus generated at test time is not counted).
    /// A replay asserts this number, so a corpus that changes size cannot go by unnoticed.</summary>
    public static int Total(string module)
    {
        lock (Gate)
        {
            Cases(module);
            return Committed[module];
        }
    }

    // one case per line ({header,"cases":[ / case, / ... / ]}): parsing line by line never holds the whole text (a 328 MB string
    // for the 164 MB action-registry oracle) beside its tree, which ran the unmutated source out of the 3 GiB heap cap
    static List<D> ReadCases(string f)
    {
        using var r = new StreamReader(new GZipStream(File.OpenRead(f), CompressionMode.Decompress), new UTF8Encoding(false));
        var head = r.ReadLine() ?? throw new InvalidDataException(f + ": empty oracle");
        if (!head.EndsWith("\"cases\":[", StringComparison.Ordinal)) throw new InvalidDataException(f + ": not one case per line");
        var count = (Num)((D)FixtureJson.Parse(head + "]}")!)["count"]!;
        LastClock = ClockOfHeader(head);
        LastClockCases = ClockCasesOfHeader(head);
        var cases = new List<D>();
        for (string? line; (line = r.ReadLine()) != "]}";)
        {
            if (line == null) throw new InvalidDataException(f + ": truncated oracle");
            cases.Add((D)ResolveSeeds(FixtureJson.Parse(line.EndsWith(',') ? line[..^1] : line), BespokeSeeds)!);
        }
        if (r.ReadLine() != null) throw new InvalidDataException(f + ": data after the cases");
        if (count.Raw != cases.Count.ToString(CultureInfo.InvariantCulture)) throw new InvalidDataException(f + $": {cases.Count} cases, header says {count.Raw}");
        return cases;
    }

    // corpora whose tests resolve their own {"$seed": label} placeholders (the label is the argument, not a key to materialize)
    static bool BespokeSeeds => LoadedModuleLoading is "ref-wallet" or "ref-actions-signbuiltins-py" or "ref-frost";
    static string? LoadedModuleLoading;

    /// <summary>Replaces every {"$seed": label[, "es256": true]} object by base64url(SHA-256("atlas-pca-conformance/" + label)), top bit of byte 0 cleared for es256.</summary>
    /// <summary>The corpus carries no BBS secret keys: {"$bbssk": n} stands for KeyGen(32 bytes of n, empty key info), which the BBS replay installs here.</summary>
    public static Func<long, object?>? BbsSecretKey;

    static object? ResolveSeeds(object? v, bool skip)
    {
        if (skip) return v;
        switch (v)
        {
            case L l:
                for (int i = 0; i < l.Count; i++) l[i] = ResolveSeeds(l[i], false);
                return l;
            case D m:
                if (m.Count == 1 && m.TryGetValue("$bbssk", out var bk) && BbsSecretKey != null) return BbsSecretKey(Long(bk));
                // {"$utf16": [code units]}: a string holding a lone surrogate
                if (m.Count == 1 && m.TryGetValue("$utf16", out var u16) && u16 is L u16l) return new string(u16l.Select(x => (char)int.Parse(((Num)x!).Raw, CultureInfo.InvariantCulture)).ToArray());
                if (m.TryGetValue("$seed", out var label) && label is string s && m.Keys.All(k => k is "$seed" or "es256" or "ec" or "ed448"))
                {
                    var p = "atlas-pca-conformance/" + s;
                    var h1 = System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(p));
                    var h2 = System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(p + "/2"));
                    var h3 = System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(p + "/3"));
                    byte[] raw = h1;
                    if (s.StartsWith("fill:", StringComparison.Ordinal) && byte.TryParse(s.AsSpan(5), NumberStyles.None, CultureInfo.InvariantCulture, out var fill)) raw = Enumerable.Repeat(fill, 32).ToArray(); // 32 bytes of one value
                    else
                    if (m.TryGetValue("ec", out var ec) && ec is "P-384") { raw = h1.Concat(h2).Concat(h3).Take(48).ToArray(); raw[0] &= 0x7F; }
                    else if (ec is "P-521") { raw = h1.Concat(h2).Concat(h3).Take(66).ToArray(); raw[0] &= 0x01; }
                    else if (m.TryGetValue("ed448", out var e4) && e4 is true) raw = h1.Concat(h2.Take(25)).ToArray();
                    else if (m.TryGetValue("es256", out var es) && es is true) raw[0] &= 0x7F;
                    return Convert.ToBase64String(raw).TrimEnd('=').Replace('+', '-').Replace('/', '_');
                }
                foreach (var k in m.Keys.ToList()) m[k] = ResolveSeeds(m[k], false);
                return m;
            default:
                return v;
        }
    }

    // corpora whose private-key cases are generated by CI (never committed) into <name>-gen.json.gz next to the main corpus (PCA_SECRET_CORPUS_DIR overrides the directory)
