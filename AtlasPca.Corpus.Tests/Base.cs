    static string? GenPath(string module, string dir)
    {
        if (!GenModules.Contains(module)) return null;
        if (Environment.GetEnvironmentVariable("PCA_SECRET_CORPUS_DIR") is { Length: > 0 } e) dir = e;
        return Path.Combine(dir, module + "-gen.json.gz");
    }

    /// <summary>Presence of <c>ref-x-gen.json.gz</c>: required when CI is "true"/"1"; locally the replay is skipped (xunit 2 has no dynamic skip, so it only reports).</summary>
    public static void RequireGenCorpus(string module)
    {
        var d = AppContext.BaseDirectory;
        for (int i = 0; i < 12 && d != null; i++, d = Path.GetDirectoryName(d))
            foreach (var dir in new[] { Path.Combine(d, "test-data"), Path.Combine(d, "AtlasPca.Corpus.Tests", "test-data") })
                if (File.Exists(Path.Combine(dir, module + ".json.gz")) && File.Exists(GenPath(module, dir)!)) return;
        var msg = "secret oracle corpus missing: " + module + "-gen.json.gz (generate with gen-secret-corpus.sh or set PCA_SECRET_CORPUS_DIR)";
        var ci = Environment.GetEnvironmentVariable("CI");
        if (ci is "true" or "1") Assert.Fail(msg);
        Console.Error.WriteLine("SKIPPED: " + msg);
    }

    public const string RsaModule = "ref-dpop-rsa";

    public static bool RsaCorpusExists()
    {
        if (Environment.GetEnvironmentVariable("PCA_DPOP_RSA_CORPUS") is { Length: > 0 } e) return File.Exists(e);
        var d = AppContext.BaseDirectory;
        for (int i = 0; i < 12 && d != null; i++, d = Path.GetDirectoryName(d))
            if (File.Exists(Path.Combine(d, "test-data", RsaModule + ".json.gz")) || File.Exists(Path.Combine(d, "AtlasPca.Corpus.Tests", "test-data", RsaModule + ".json.gz"))) return true;
        return false;
    }

    public static IEnumerable<D> Of(string module, string fn)
    {
        var main = Cases(module).Where(c => (string)c["fn"]! == fn || (string)c["fn"]! == fn + "@suspect").ToList();
        // the generated RSA DPoP cases replay through the same function table when present (RefDpopTests.RsaCorpusIsPresent enforces presence)
        if (module == "ref-dpop" && RsaCorpusExists())
            main.AddRange(Cases(RsaModule).Where(c => (string)c["fn"]! == fn || (string)c["fn"]! == fn + "@suspect").ToList());
        return main;
    }
    public static L Args(D c) => c["args"] is D single ? new L { single } : (L)c["args"]!; // a corpus may write its one argument without the list

    // ---- argument helpers ----
    public static byte[] Bytes(object? a) => Pca.B64uDecode(((D)a!)["$bytes"]) ?? throw new InvalidDataException("bad $bytes");
    public static bool IsBytes(object? a) => a is D m && m.Count == 1 && m.ContainsKey("$bytes");
    public static long Long(object? a) => IntentJs.Lng(a);
    public static bool IsJsonInt(object? a) => a is Num n && long.TryParse(n.Raw, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out _);
    public static object? Deep(object? a) => a switch
    {
        D m => m.ToDictionary(e => e.Key, e => Deep(e.Value)),
        L l => l.Select(Deep).ToList(),
        _ => a,
    };

    // ---- result -> JSON tree ----
    public static object? Json(object? v) => v switch
    {
        null => null,
        _ when ReferenceEquals(v, AtlasPca.InteropJs.JsX.Undef) => null,
        string or bool or Num => v,
        byte[] b => new D { ["$bytes"] = Pca.B64u(b) },
        int or long or short or uint or ulong or double or float or decimal => IntentJs.Normalize(new Num(Convert.ToString(v, CultureInfo.InvariantCulture)!)),
        IDictionary m => m.Keys.Cast<object>().Where(k => !ReferenceEquals(m[k], AtlasPca.InteropJs.JsX.Undef)).ToDictionary(k => k.ToString()!, k => Json(m[k])), // an undefined member is not in the JSON
        IEnumerable e => e.Cast<object?>().Select(Json).ToList(),
        _ => throw new InvalidOperationException("Base.Json: map " + v.GetType() + " explicitly"),
    };

    /// <summary>Deterministic text of a JSON tree: sorted keys (ordinal), numbers as JavaScript prints them, every non-ASCII code unit
    /// escaped (so lone surrogates compare too). Equal text = equal value.</summary>
    public static string Show(object? v)
    {
        var sb = new StringBuilder();
        void S(string s)
        {
            sb.Append('"');
            foreach (var ch in s)
                if (ch == '"' || ch == '\\') sb.Append('\\').Append(ch);
                else if (ch < 0x20 || ch > 0x7e) sb.Append("\\u").Append(((int)ch).ToString("x4"));
                else sb.Append(ch);
            sb.Append('"');
        }
        void W(object? x)
        {
            switch (x)
            {
                case null: sb.Append("null"); break;
                case bool b: sb.Append(b ? "true" : "false"); break;
                case string s: S(s); break;
                case Num n: sb.Append(IntentJs.NormNum(n.Raw).Raw); break;
                case L l: sb.Append('['); for (int i = 0; i < l.Count; i++) { if (i > 0) sb.Append(','); W(l[i]); } sb.Append(']'); break;
                case D m:
                    sb.Append('{');
                    var first = true;
                    foreach (var k in m.Keys.OrderBy(k => k, StringComparer.Ordinal))
                    {
                        if (!first) sb.Append(','); first = false;
                        S(k); sb.Append(':'); W(m[k]);
                    }
                    sb.Append('}');
                    break;
                default: W(Json(x)); break;
            }
        }
        W(v);
        return sb.ToString();
    }

    public static bool Eq(object? want, object? have) => Show(want) == Show(Json(have));

    static readonly System.Text.RegularExpressions.Regex EngineCrashRe = new(
        "Cannot read propert(y|ies) of (null|undefined)|is not a function|is not iterable|Cannot convert undefined or null to object|Cannot destructure|Cannot use 'in' operator|Cannot create property|Reduce of empty array|is not an object|Cannot mix BigInt|Do not know how to serialize a BigInt|Converting circular structure|Invalid array length|Maximum call stack",
        System.Text.RegularExpressions.RegexOptions.CultureInvariant);

    /// <summary>A raw JavaScript-engine crash text on hostile input: the case passes iff the native refuses, whatever it says (never a Node error code).</summary>
    public static bool IsEngineCrash(string? message) => message != null && EngineCrashRe.IsMatch(message);

    public static bool Throws(D c, out string? code)
    {
        code = null;
        if (c["out"] is D o && o.ContainsKey("$throws"))
        {
            // the engine-crash rule: refusal only, no message and no code compared
            code = IsEngineCrash(o["$throws"] as string) ? null : o.GetValueOrDefault("code") as string;
            return true;
        }
        return false;
    }

    /// <summary>The exception's Code property, else a leading "code: " of its message (the convention of the untyped .NET refusals).</summary>
    static string? CodeOf(Exception e)
    {
        if (e.GetType().GetProperty("Code")?.GetValue(e) is string c) return c;
        var i = e.Message.IndexOf(": ", StringComparison.Ordinal);
        return i > 0 && e.Message[..i].All(ch => ch is >= 'a' and <= 'z' or '_') ? e.Message[..i] : null;
    }

    /// <summary>Replay every case of (module, fn): <paramref name="run"/> maps the args to the native call and returns its result
    /// (or <see cref="Refused"/>); <paramref name="eq"/> overrides the comparison (default: JSON equality with out);
    /// <paramref name="skip"/> returns a reason to skip a case (counted, listed in the output). Returns the number compared.</summary>
    public static int Check(string module, string fn, Func<L, object?> run, Func<D, object?, bool>? eq = null, Func<D, string?>? skip = null, int min = 1)
    {
        // the replay runs under the clock the corpus generator ran under (its header's clockMs), wherever the native reads a clock of its own
        var clock = (long)ClockMs(module);
        var previous = AtlasPca.ReplayClock.Ms;
        AtlasPca.ReplayClock.Ms = () => clock;
        try { return CheckCases(module, fn, run, eq, skip, min); }
        finally { AtlasPca.ReplayClock.Ms = previous; }
    }

    static int CheckCases(string module, string fn, Func<L, object?> run, Func<D, object?, bool>? eq, Func<D, string?>? skip, int min)
    {
        var bad = new List<string>(); var suspect = new List<string>(); int n = 0, skipped = 0;
        foreach (var c in Of(module, fn))
        {
            var name = (string)c["name"]!;
            if (skip?.Invoke(c) is string why) { skipped++; continue; }
            n++;
            var isSuspect = ((string)c["fn"]!).EndsWith("@suspect", StringComparison.Ordinal);
            var sink = isSuspect ? suspect : bad;
            var wantThrow = Throws(c, out var code);
            object? have; Exception? ex = null;
            try { have = run(Args(c)); } catch (Exception e) { have = null; ex = e; }
            if (wantThrow)
            {
                if (ex == null && !ReferenceEquals(have, Refused)) sink.Add($"{name}\n   want throw {Show(c["out"])}\n   have {Safe(have)}");
                else if (code != null && ex != null && CodeOf(ex) is string hc && hc != code) sink.Add($"{name}\n   want code {code}\n   have code {hc}: {ex.Message}");
                else if (code != null && ex != null && CodeOf(ex) == null) sink.Add($"{name}\n   want code {code}\n   have {ex.GetType().Name}: {ex.Message}");
                continue;
            }
            if (ex != null) { sink.Add($"{name}\n   want {Show(c["out"])}\n   threw {ex.GetType().Name}: {ex.Message}"); continue; }
            bool ok;
            try { ok = eq != null ? eq(c, have) : !ReferenceEquals(have, Refused) && Eq(c["out"], have); }
            catch (Exception e) { ok = false; have = "compare threw " + e.Message; }
            if (!ok) { var ws = Show(c["out"]); var hs = Safe(have); sink.Add($"{name}\n   want {ws}\n   have {hs}{FirstDiff(ws, hs)}"); }
        }
        if (suspect.Count > 0) Console.WriteLine($"base {module}/{fn}: {suspect.Count} @suspect divergence(s) (reported, not failed):\n" + string.Join("\n", suspect.Take(10)));
        Assert.True(bad.Count == 0, $"{module}/{fn}: {bad.Count} of {n} divergent ({skipped} skipped):\n" + string.Join("\n", bad.Take(40)));
        Assert.True(n >= min, $"{module}/{fn}: only {n} cases compared ({skipped} skipped)");
        return n;
    }

    /// <summary>Where the two renderings first differ, with the text around it: the whole values are long and the log keeps only their start.</summary>
    static string FirstDiff(string a, string b)
    {
        int i = 0;
        while (i < a.Length && i < b.Length && a[i] == b[i]) i++;
        // Escaped so a hidden difference (a lookalike character, a control character) is visible; key order is the text order.
        static string Esc(string x) { var sb = new System.Text.StringBuilder(); foreach (var ch in x) sb.Append(ch < 0x20 || ch > 0x7e ? "\\u" + ((int)ch).ToString("x4") : ch.ToString()); return sb.ToString(); }
        if (i == a.Length && i == b.Length) return "\n   renderings are textually identical; the comparer still differs\n   want(escaped) " + Esc(a) + "\n   have(escaped) " + Esc(b);
        string Win(string x) => Esc(x.Substring(Math.Max(0, i - 40), Math.Min(x.Length, i + 80) - Math.Max(0, i - 40)));
        return $"\n   diff @{i}: want ...{Win(a)}...\n   diff @{i}: have ...{Win(b)}...";
    }

    static string Safe(object? h)
    {
        if (ReferenceEquals(h, Refused)) return "<refused>";
        try { return Show(Json(h)); } catch { return h?.ToString() ?? "null"; }
    }

    /// <summary>Every fn of the module is either checked by a [Fact] or listed as skipped with a reason.</summary>
    public static void Covers(string module, IEnumerable<string> handled)
    {
        var h = new HashSet<string>(handled);
        var missing = Cases(module).Select(c => ((string)c["fn"]!).Replace("@suspect", "")).Distinct().Where(f => !h.Contains(f)).ToList();
        Assert.True(missing.Count == 0, $"{module}: fn(s) with no test: {string.Join(", ", missing)}");
    }
}
