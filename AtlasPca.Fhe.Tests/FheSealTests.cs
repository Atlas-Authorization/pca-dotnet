using System.IO.Compression;
using System.Text.Json;
using AtlasPca.Fhe;
using Xunit;

namespace AtlasPca.Fhe.Tests;

public class FheSealTests
{
    static readonly Lazy<JsonElement> Corpus = new(() =>
    {
        var path = Environment.GetEnvironmentVariable("PCA_FHE_SEAL_CORPUS");
        Assert.False(string.IsNullOrEmpty(path), "PCA_FHE_SEAL_CORPUS must point at the node-seal corpus (generated by the oracle in CI)");
        using var fs = File.OpenRead(path!);
        using var gz = new GZipStream(fs, CompressionMode.Decompress);
        return JsonDocument.Parse(gz).RootElement.Clone();
    });

    static long[] Longs(JsonElement e) => e.EnumerateArray().Select(x => x.GetInt64()).ToArray();

    static FheRiskPolicy Policy(JsonElement p) => new(p.GetProperty("scale").GetInt64(), p.GetProperty("dim").GetInt64(),
        Longs(p.GetProperty("weightsScaled")), Longs(p.GetProperty("kappaWeightsScaled")), p.GetProperty("budgetScaled").GetInt64(), p.GetProperty("kappa").GetDouble());

    [Fact]
    public void CorpusParametersMatchTheNativeContext()
    {
        var seal = Corpus.Value.GetProperty("seal");
        Assert.Equal(FheSeal.PolyModulusDegree, seal.GetProperty("polyModulusDegree").GetInt32());
        Assert.Equal(FheSeal.PlainModulus, seal.GetProperty("plainModulus").GetInt64());
        using var ctx = FheSeal.Ctx.Create(); // throws on any plain-modulus drift
    }

    // The evaluation is deterministic given (ciphertext, Galois keys, policy): the native result must equal the reference's, byte for byte, once both are re-saved uncompressed.
    [Fact]
    public void EvaluatesTheReferenceCiphertextsToTheReferenceResults()
    {
        var root = Corpus.Value;
        var keys = new FheEvalKeys(root.GetProperty("publicKey").GetString()!, root.GetProperty("relinKeys").GetString()!, root.GetProperty("galoisKeys").GetString()!);
        int n = 0;
        foreach (var c in root.GetProperty("cases").EnumerateArray())
        {
            var name = c.GetProperty("name").GetString();
            var gate = FheSeal.EvalRiskGate(keys, c.GetProperty("encInputs").GetString()!, Policy(c.GetProperty("policy")));
            Assert.True(FheSeal.CanonicalCipher(c.GetProperty("encRiskRaw").GetString()!).AsSpan().SequenceEqual(FheSeal.CanonicalCipher(gate.EncRiskRaw)), $"encRiskRaw differs in {name}");
            Assert.True(FheSeal.CanonicalCipher(c.GetProperty("encSlack").GetString()!).AsSpan().SequenceEqual(FheSeal.CanonicalCipher(gate.EncSlack)), $"encSlack differs in {name}");
            n++;
        }
        Assert.True(n >= 6);
    }

    public static IEnumerable<object[]> Roundtrips() => new[]
    {
        new object[] { new long[] { 100, 900, 100, 100, 100, 100 }, 1.0, 0.6 },
        new object[] { new long[] { 1000, 1000, 1000, 1000, 1000, 1000 }, 1.0, 0.5 },
        new object[] { new long[] { 0, 0, 0, 0, 0, 0 }, 1.5, 0.25 },
    };

    static FheRiskPolicy MakePolicy(double kappa, double budget)
    {
        var w = new[] { 0.25, 0.2, 0.2, 0.2, 0.1, 0.05 };
        return new FheRiskPolicy(1000, 6, w.Select(v => (long)Math.Round(v * 1000)).ToArray(), w.Select(v => (long)Math.Round(kappa * v * 1000)).ToArray(), (long)Math.Round(budget * 1e6), kappa);
    }

    [Theory]
    [MemberData(nameof(Roundtrips))]
    public void NativeKeygenEncryptEvaluateDecryptMatchesPlaintextArithmetic(long[] x, double kappa, double budget)
    {
        var keys = FheSeal.Keygen();
        var policy = MakePolicy(kappa, budget);
        var enc = FheSeal.EncryptRiskInputs(keys.PublicKey, x);
        var gate = FheSeal.EvalRiskGate(new FheEvalKeys(keys.PublicKey, keys.RelinKeys, keys.GaloisKeys), enc, policy);
        var v = FheSeal.DecryptVerdict(keys.SecretKey, gate.EncRiskRaw, gate.EncSlack, policy);
        long raw = 0, kr = 0;
        for (int i = 0; i < 6; i++) { raw += policy.WeightsScaled[i] * x[i]; kr += policy.KappaWeightsScaled[i] * x[i]; }
        Assert.Equal(raw, v.RScaled);
        Assert.Equal(policy.BudgetScaled - kr, v.Slack);
        Assert.Equal(v.Slack >= 0, v.Admit);
    }

    [Fact]
    public void AllZeroWeightsEvaluateToZeroInsteadOfCrashing()
    {
        var keys = FheSeal.Keygen();
        var policy = new FheRiskPolicy(1000, 6, new long[6], new long[6], 5000, 1);
        var enc = FheSeal.EncryptRiskInputs(keys.PublicKey, new long[] { 5, 5, 5, 5, 5, 5 });
        var gate = FheSeal.EvalRiskGate(new FheEvalKeys(keys.PublicKey, keys.RelinKeys, keys.GaloisKeys), enc, policy);
        var v = FheSeal.DecryptVerdict(keys.SecretKey, gate.EncRiskRaw, gate.EncSlack, policy);
        Assert.Equal(0, v.RScaled);
        Assert.Equal(5000, v.Slack);
        Assert.True(v.Admit);
    }

    [Fact]
    public void WrongKeyFailsClosed()
    {
        var a = FheSeal.Keygen();
        var b = FheSeal.Keygen();
        var policy = MakePolicy(1, 0.6);
        var gate = FheSeal.EvalRiskGate(new FheEvalKeys(a.PublicKey, a.RelinKeys, a.GaloisKeys), FheSeal.EncryptRiskInputs(a.PublicKey, new long[] { 1, 2, 3, 4, 5, 6 }), policy);
        Assert.Throws<InvalidOperationException>(() => FheSeal.DecryptVerdict(b.SecretKey, gate.EncRiskRaw, gate.EncSlack, policy));
    }

    [Fact]
    public void MalformedBlobsAreRefusedBeforeSealParsesThem()
    {
        var keys = FheSeal.Keygen();
        var good = FheSeal.EncryptRiskInputs(keys.PublicKey, new long[] { 1, 2, 3, 4, 5, 6 });
        var bytes = Convert.FromBase64String(good);
        Assert.Throws<ArgumentException>(() => FheSeal.AssertSealBlob(Convert.ToBase64String(bytes[..^4]), "x"));
        Assert.Throws<ArgumentException>(() => FheSeal.AssertSealBlob(Convert.ToBase64String(bytes.Concat(new byte[] { 0, 0, 0 }).ToArray()), "x"));
        Assert.Throws<ArgumentException>(() => FheSeal.AssertSealBlob("AAAA", "x"));
        Assert.Throws<ArgumentException>(() => FheSeal.AssertSealBlob(new string('A', 64), "x"));
    }

    [Fact]
    public void PolicyAndInputBoundsAreEnforced()
    {
        Assert.Throws<ArgumentException>(() => FheSeal.RequirePolicy(new FheRiskPolicy(1000, 5, new long[6], new long[6], 0, 1)));
        Assert.Throws<ArgumentException>(() => FheSeal.RequirePolicy(new FheRiskPolicy(1000, 6, new long[6], new long[6], FheSeal.SignedBound, 1)));
        Assert.Throws<ArgumentException>(() => FheSeal.RequirePolicy(new FheRiskPolicy(0, 6, new long[6], new long[6], 0, 1)));
        Assert.Throws<ArgumentException>(() => FheSeal.RequirePolicy(new FheRiskPolicy(1000, 6, new long[5], new long[6], 0, 1)));
        Assert.Throws<ArgumentException>(() => FheSeal.EncryptRiskInputs("x", new long[] { -1, 0, 0, 0, 0, 0 }));
    }
}
